#!/usr/bin/env bash
# Generate demos and their videos in one call.
#
#   bash experiments/policy_data/make_demos.sh <task> <n_demos> <out_dir> [options]
#
#   <task>     annotated source dataset: datasets/annotated_dataset/annotated_dataset_<task>.hdf5 (e.g. franka_towel)
#   <n_demos>  number of successful demos
#   <out_dir>  output folder: <task>_n<n_demos>_seed<seed>.hdf5, *_failed.hdf5, *_instance_ids.json, videos/,
#              sheet_first.png, sheet_last.png, summary.csv, summary.txt, run_config.json, gen.log, videos.log
#   options    --seed N (default 1)   --gpu N (physical GPU index, default 0)   --num_envs N (default 1)
#              --wrist_focal MM (default 12)   --image_size PX (default 512)   --no_raw   --all_frames
#              --room_camera NAME / --wrist_camera NAME (default agentview_image / robot0_eye_in_hand_image)
#
# Run inside the SoftMimicGen environment (conda activate softmimicgen).
set -eo pipefail
usage() { sed -n '2,14p' "$0"; exit 1; }
[ $# -ge 3 ] || usage
TASK="$1"; N="$2"; OUT="$3"; shift 3
[[ "$OUT" = /* ]] || OUT="$PWD/$OUT"
SEED=1; GPU=0; NUM_ENVS=1; WRIST_FOCAL=12; IMAGE_SIZE=512; RAW=""; FRAMES=""
ROOM_CAM=agentview_image; WRIST_CAM=robot0_eye_in_hand_image
while [ $# -gt 0 ]; do
  case "$1" in
    --seed) SEED="${2:?--seed needs a value}"; shift 2 ;;
    --gpu) GPU="${2:?--gpu needs a value}"; shift 2 ;;
    --num_envs) NUM_ENVS="${2:?--num_envs needs a value}"; shift 2 ;;
    --wrist_focal) WRIST_FOCAL="${2:?--wrist_focal needs a value}"; shift 2 ;;
    --image_size) IMAGE_SIZE="${2:?--image_size needs a value}"; shift 2 ;;
    --room_camera) ROOM_CAM="${2:?--room_camera needs a value}"; shift 2 ;;
    --wrist_camera) WRIST_CAM="${2:?--wrist_camera needs a value}"; shift 2 ;;
    --no_raw) RAW="--no_raw"; shift ;;
    --all_frames) FRAMES="--all_frames"; shift ;;
    *) echo "unknown option: $1"; usage ;;
  esac
done
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
cd "$ROOT"
IN="datasets/annotated_dataset/annotated_dataset_${TASK}.hdf5"
[ -f "$IN" ] || { echo "input not found: $IN"; exit 1; }
NAME="${TASK}_n${N}_seed${SEED}"
mkdir -p "$OUT"
[ -e "$OUT/$NAME.hdf5" ] && { echo "exists: $OUT/$NAME.hdf5"; exit 1; }

# CUDA sees only the chosen GPU (as cuda:0). The renderer takes the physical index.
export CUDA_VISIBLE_DEVICES="$GPU"
KIT_ARGS="--/renderer/multiGpu/enabled=false --/renderer/activeGpu=$GPU"
START=$(date +%s)
COMMIT="$(git -c safe.directory='*' rev-parse --short HEAD 2>/dev/null || echo unknown)"
python - "$OUT/run_config.json" <<PY
import json, sys
json.dump({"task": "$TASK", "n_demos": int("$N"), "seed": int("$SEED"), "gpu": "$GPU", "num_envs": int("$NUM_ENVS"),
           "wrist_focal_mm": float("$WRIST_FOCAL"), "image_size": int("$IMAGE_SIZE"), "raw": "$RAW" == "",
           "room_camera": "$ROOM_CAM", "wrist_camera": "$WRIST_CAM", "input": "$ROOT/$IN", "output": "$OUT/$NAME.hdf5",
           "started": "$(date -Iseconds)", "git_commit": "$COMMIT"}, open(sys.argv[1], "w"), indent=1)
PY
echo "policy_data: $TASK, $N demos, seed $SEED, GPU $GPU -> $OUT/$NAME.hdf5 (log: $OUT/gen.log)"
set +e
python "$HERE/generate_demos.py" --device cuda:0 "--kit_args=$KIT_ARGS" \
  --input_file "$IN" --output_file "$OUT/$NAME.hdf5" --generation_num_trials "$N" --num_envs "$NUM_ENVS" \
  --seed "$SEED" --wrist_focal "$WRIST_FOCAL" --image_size "$IMAGE_SIZE" $RAW \
  --room_camera "$ROOM_CAM" --wrist_camera "$WRIST_CAM" --enable_cameras --headless 2>&1 | tee "$OUT/gen.log"
GEN_RC=${PIPESTATUS[0]}
set -e
GEN_END=$(date +%s)
# The recorder creates the hdf5 at start. The demo count shows whether the generation finished.
DEMOS=$(python -c "import h5py, sys; print(len(h5py.File(sys.argv[1], 'r')['data']))" "$OUT/$NAME.hdf5" 2>/dev/null || echo 0)
[ "$DEMOS" -ge "$N" ] || { echo "generation failed: $DEMOS/$N demos, python exit $GEN_RC (see $OUT/gen.log)"; exit 1; }

python "$HERE/make_videos.py" "$OUT/$NAME.hdf5" --out "$OUT" $FRAMES 2>&1 | tee "$OUT/videos.log"
END=$(date +%s)
{
  echo "dataset:     $OUT/$NAME.hdf5 ($DEMOS demos)"
  echo "result:      $(grep -o '[0-9]*/[0-9]* ([0-9.]*%) successful demos generated by mimic' "$OUT/gen.log" | tail -1)"
  echo "generation:  $((GEN_END - START)) s (python exit $GEN_RC), videos: $((END - GEN_END)) s"
  echo "settings:    seed $SEED, GPU $GPU, wrist ${WRIST_FOCAL} mm, ${IMAGE_SIZE}x${IMAGE_SIZE}, raw ${RAW:-on}, num_envs $NUM_ENVS, cameras $ROOM_CAM / $WRIST_CAM"
} | tee "$OUT/summary.txt"
