def ref_variation(k: int, seed: int, task: str, mode: str | None = None) -> str:
    """Variation sentences for reference image k (1-based). Image 1 is faithful. Image k > 1 draws, with
    random.Random(f"{task}:{seed + k - 1}"), one entry per REF_AXES axis plus a colour and material for the task's
    manipulated object (TASKS[task]["object"], "materials", optional "colours"), so a run is reproducible, every image
    differs, and image k of different tasks gets different combinations.
    TASKS[task]["variation"] = "weak" keeps the background and table faithful (REF_FAITHFUL) and varies only lighting,
    camera look and the object: scenes with little structure (a rope on a bare table) get re-composed by
    environment/table sentences (2026-09-14, franka_rope), whereas towel scenes keep their layout under "full"."""
    if k == 1:
        return REF_FAITHFUL
    rng = random.Random(f"{task}:{seed + k - 1}")
    cfg = TASKS[task]
    weak = (mode or cfg.get("variation", "full")) == "weak"  # mode: force "weak" (make_refs.py fallback) or "full"
    parts = [REF_FAITHFUL] if weak else []
    parts += [rng.choice(v) for axis, v in REF_AXES.items() if not (weak and axis in ("environment", "table", "robot"))]
    parts.append(f"The {cfg['object']} is {rng.choice(cfg.get('colours', OBJECT_COLOURS))} {rng.choice(cfg['materials'])}.")
    return " ".join(parts)


def object_look(task: str, k: int, seed: int) -> str:
    """'<colour> <material>' of the manipulated object for Wan variation k (own rng stream, so it does not repeat the
    reference-image variations)."""
    rng = random.Random(f"obj:{task}:{seed + k - 1}")
    cfg = TASKS[task]
    return f"{rng.choice(cfg.get('colours', OBJECT_COLOURS))} {rng.choice(cfg['materials'])}"


def wan_object_prompt(task: str, k: int, seed: int) -> str:
    """Wan prompt for make_wan.py --n_obj: the scene with the object's colour, material and shape spelled out (the empty
    reference anchors robot, table and background, CRAFT's object-colour augmentation)."""
    cfg = TASKS[task]
    return cfg["scene"].format(object=cfg["object_shape"].format(look=object_look(task, k, seed))) + _TAIL


def wan_variation_prompt(task: str, k: int, seed: int) -> str:
    """Wan prompt for make_wan.py --n_var (no reference image, CRAFT's background augmentation): scene with the object
    look plus one sentence per REF_AXES axis (environment, table, robot condition, lighting, camera look)."""
    rng = random.Random(f"var:{task}:{seed + k - 1}")
    cfg = TASKS[task]
    scene = cfg["scene"].format(object=cfg["object_shape"].format(look=object_look(task, k, seed)))
    return scene + ". " + " ".join(rng.choice(v) for v in REF_AXES.values()) + " Realistic video, static camera."


def run_dir(task: str, tag: str) -> str:
    """experiments/wan_canny/runs/<tag>/<task>_<tag>: one folder per tag, one subfolder per task."""
    return os.path.join(RUNS_DIR, tag, f"{task}_{tag}")


def task_of(name: str) -> str:
    """Task key for a run dir or prefix such as 'franka_towel_v6' (longest key that prefixes the name)."""
    base = os.path.basename(os.path.normpath(name))
    hits = [k for k in TASKS if base == k or base.startswith(k + "_")]
    if not hits:
        raise KeyError(f"no task in tasks.TASKS matches '{base}' (known: {', '.join(TASKS)})")
    return max(hits, key=len)
