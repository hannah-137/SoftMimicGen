    p.add_argument("--cfg", type=float, default=3.5)
    p.add_argument("--shift", type=float, default=8.0)
    p.add_argument("--size", default=None, help="video size WxH or N (square); default = size of <prefix>_ref_sim.png")
    p.add_argument("--frames", type=int, default=81)
    p.add_argument("--force", action="store_true", help="regenerate existing outputs")
    p.add_argument("--dry_run", action="store_true", help="print the jobs, do not contact ComfyUI")
    p.add_argument("--n_obj", type=int, default=0, help="object colour/material variations: images/<prefix>_ref_empty.png + prompt -> _oNN")
    p.add_argument("--n_var", type=int, default=0, help="background/table/lighting variations: no reference image, prompt only -> _pNN")
    p.add_argument("--prefix", default=None, help="file prefix (default: run_dir folder name; single run dir only)")
    p.add_argument("--task", default=None, help="task key in tasks.TASKS (default: derived from the prefix; single run dir only)")
    p.add_argument("--comfy_url", default="http://127.0.0.1:8188",
                   help="one or more ComfyUI servers, comma-separated; videos run on all of them at once")
    p.add_argument("--comfy_dir", default="/workspace/tools/ComfyUI")
    p.add_argument("--comfy_python", default="/opt/miniconda3/envs/comfyui/bin/python")
    p.add_argument("--comfy_gpu", default="1", help="GPU per auto-started server, comma-separated like --comfy_url (-1: let ComfyUI choose)")
    p.add_argument("--comfy_log", default="logs/comfyui.log")
    p.add_argument("--template", default=TEMPLATE)
    p.add_argument("--timeout", type=float, default=1800, help="seconds to wait per video")
    p.add_argument("--no_check", action="store_true", help="skip the layout check (quality.py) and keep every video")
    p.add_argument("--retries", type=int, default=3, help="attempts per video (new seed each) before it counts as failed")
    a = p.parse_args()
    if len(a.run_dir) > 1 and (a.prefix or a.task):
        p.error("--prefix/--task only work with a single run dir")
    try:
        servers = servers_from(a.comfy_url, a.comfy_gpu, a.comfy_log)  # refuses GPU 0 before anything else
    except ValueError as e:
        p.error(str(e))
    controls = [c.strip() for c in a.controls.split(",") if c.strip()]
    jobs, need_ref = [], []
    for rd in a.run_dir:
        try:
            jobs += plan(rd, controls, a.ref, a.prompt, a.negative, a.seed, a.steps, a.cfg, a.shift, a.size, a.frames,
                         a.force, a.prefix, a.task, a.template, a.n_obj, a.n_var)
        except FileNotFoundError as e:
            if len(a.run_dir) == 1:
                raise
            print(f"wan: {rd}: skipped: {str(e).splitlines()[0]}", flush=True)
            need_ref.append(rd)
    print(f"wan: {len(jobs)} videos from {len(a.run_dir)} run dir(s) on {len(servers)} server(s): "
          + ", ".join(f"{u} (GPU {g})" for u, g, _ in servers), flush=True)
    if a.dry_run:
        for j in jobs:
            print(f"--- {j['prefix']}:{j['control']}{j['suffix']} ({j['mode']}, ref={os.path.basename(j['ref']) if j['ref'] else 'none'}): {j['dst']}\n    prompt: {j['prompt']}")
        sys.exit(0)
    out = execute(jobs, servers, a.comfy_dir, a.comfy_python, a.timeout, not a.no_check, a.retries) if jobs else {}
    failed = [k for k, v in out.items() if v is None]
    print(f"wan: done: {len(out) - len(failed)} ok, {len(failed)} failed" + (f": {failed}" if failed else ""), flush=True)
    sys.exit(1 if failed or need_ref else 0)
