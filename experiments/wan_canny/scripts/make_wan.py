"""Stage 4 of the Wan pipeline: one Wan 2.2 Fun-Control video per (reference image, control video) of a run dir, through
the ComfyUI API.

  python experiments/wan_canny/scripts/make_wan.py <run_dir> [<run_dir> ...] [--controls canny,geoedge,...] [--ref PNG]
      [--prompt TEXT] [--n_obj M] [--n_var K] [--comfy_url URL[,URL]] [--comfy_gpu G[,G]]
      [--seed 0] [--steps 20] [--cfg 3.5] [--shift 8] [--size WxH] [--frames 81] [--force] [--dry_run]

<run_dir> is experiments/wan_canny/runs/<tag>/<task>_<tag>/ with the control videos in edges/<prefix>_<control>.mp4 (prefix =
folder name, override with --prefix). For every (reference image, control) pair this writes
wans/<prefix>_wan_<control><ref suffix>.mp4 and .json (every parameter, prompt id, timing).
Reference images: every images/<prefix>_ref_ai*.png, i.e. <prefix>_ref_ai.png (suffix "") and/or
<prefix>_ref_ai_01.png, _02.png, ... (suffix _01, _02, ...). Each is a photorealistic version of
<prefix>_ref_sim.png (the simulator frame 0 written by make_source.py), same composition, either made by the user
with an image model and dropped into the folder or generated by make_refs.py. Without any this stage stops (NEED_REF);
it never falls back to the simulator frame on its own.
Variations (CRAFT-style, 2026-09-14): --n_obj M makes M videos per control from images/<prefix>_ref_empty.png (the scene
without the object, make_refs.py --empty) with the object's colour/material/shape in the prompt (tasks.wan_object_prompt),
named _wan_<control>_o01..; --n_var K makes K videos per control with no reference image and a prompt that also sets
environment, table, robot condition, lighting and camera look (tasks.wan_variation_prompt), named _wan_<control>_p01...
Both draw from the image seed (--seed), so a run is reproducible. Every json records mode and prompt.
Layout check (2026-09-14): every finished video is scored with quality.check_video (robot and object outlines on all
frames vs the simulator). A failing video moves to wans/rejected/ and is made again with the next seed, up to --retries
attempts. A reference slot that make_refs.py could not fill (<name>.fallback.json) becomes one more prompt-only video.
--ref PATH uses another file, --ref sim uses <prefix>_ref_sim.png explicitly (sim-look experiments), --ref none drops the
reference image so the prompt alone sets the appearance (CRAFT's background variation; the control video fixes the layout).
The prompt comes from tasks.TASKS[<task>] unless --prompt is given. Existing outputs are skipped unless --force.
Video size: taken from <prefix>_ref_sim.png, i.e. the camera's own size (512x512 for most tasks, 512x320 for the
humanoid POV camera); --size WxH overrides. Wan needs multiples of 16. The reference image should have the same
aspect ratio (the Wan node stretches it to the video size).

ComfyUI: talks to --comfy_url (default http://127.0.0.1:8188). If nothing answers there, starts a server from
--comfy_dir on --comfy_gpu (default GPU 1: Isaac Sim only renders on GPU 0 here and Wan 14B peaks at ~20 GB, so the
two cannot share a GPU) and leaves it running. Several servers (--comfy_url a,b --comfy_gpu 1,0) run at once: one
worker per server takes the next video from a shared queue, and several run dirs share that queue (docker/gen.sh
passes every task of a batch in one call and one server per GPU). The graph is workflows/wan22_fun_control_api.json (the ComfyUI
"Wan 2.2 14B Fun Control" template in API form); nodes are found by class_type, so the file can be re-exported from
the UI ("Export (API)") as long as it keeps the same node types. Standard library only, no torch needed.
"""
