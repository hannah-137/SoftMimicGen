def plan(run_dir: str, controls=None, ref: str | None = None, prompt: str | None = None, negative: str = NEGATIVE_PROMPT,
         seed: int = 0, steps: int = 20, cfg: float = 3.5, shift: float = 8.0, size: str | None = None, frames: int = 81,
         force: bool = False, prefix: str | None = None, task: str | None = None, template: str = TEMPLATE,
         n_obj: int = 0, n_var: int = 0) -> list[dict]:
    """All Wan videos still to make for one run dir, as self-contained job dicts (no ComfyUI contact)."""
    run_dir = os.path.normpath(run_dir)
    prefix = prefix or os.path.basename(run_dir)
    task = task or task_of(prefix)
    prompt = prompt if prompt is not None else TASKS[task]["prompt"]
    if TASKS[task].get("negative_extra") and negative == NEGATIVE_PROMPT:
        negative = negative + ", " + TASKS[task]["negative_extra"]
    controls = list(controls or CONTROLS)
    d_img, d_edge, d_wan = (os.path.join(run_dir, SUBDIRS[k]) for k in ("images", "edges", "wans"))
    ref_sim = os.path.join(d_img, f"{prefix}_ref_sim.png")
    if ref == "sim":
        refs = [(ref_sim, "")]
    elif ref == "none":
        refs = [(None, "")]  # prompt-only appearance, control video fixes the layout
    elif ref:
        refs = [(ref, "")]
    else:
        refs = find_refs(d_img, prefix)
        fallback_any = glob.glob(os.path.join(d_img, f"{prefix}_ref_*.fallback.json"))
        if not refs and not (n_obj or n_var or fallback_any):
            raise FileNotFoundError(
                f"NEED_REF: no reference image in {d_img}/\n"
                f"  make photorealistic versions of {ref_sim} (same composition) and save them as {prefix}_ref_ai.png "
                f"or {prefix}_ref_ai_01.png, _02.png, ... there, then rerun (docker/gen.sh <task> <tag> --from 4). "
                f"--ref sim uses the simulator frame."
            )
    for r, _ in refs:
        if r is not None and not os.path.isfile(r):
            raise FileNotFoundError(f"reference image not found: {r}")
    width, height = parse_size(size) or (png_size(ref_sim) if os.path.isfile(ref_sim) else (512, 512))
    if width % 16 or height % 16:
        raise ValueError(f"video size {width}x{height} must be a multiple of 16 (Wan)")
    for r, _ in refs:
        if r is not None and r.lower().endswith(".png"):
            rw, rh = png_size(r)
            if abs(rw / rh - width / height) > 0.02:
                print(f"wan: WARNING reference image {r} is {rw}x{rh}, video is {width}x{height}: the Wan node will stretch it", flush=True)

    srcs = {}
    for c in controls:
        src = os.path.join(d_edge, f"{prefix}_{c}.mp4")
        if os.path.isfile(src):
            srcs[c] = src
        else:
            print(f"wan: {prefix}: {c}: control video missing ({src}), skipped")
    # one Wan video per (reference, control): wans/<prefix>_wan_<control><suffix>.mp4, suffix = reference suffix for the
    # reference images, _oNN for --n_obj (empty reference + object look prompt), _pNN for --n_var (no reference + variation prompt)
    kinds = [(r, sfx, prompt, "ref") for r, sfx in refs]
    # make_refs.py writes <name>.fallback.json when no image passed the layout check: that slot becomes one more
    # prompt-only video, and a failed empty reference turns every object variation into a prompt-only one
    fallback_refs = sorted(glob.glob(os.path.join(d_img, f"{prefix}_ref_ai_*.fallback.json")))
    if os.path.isfile(os.path.join(d_img, f"{prefix}_ref_empty.fallback.json")) and n_obj:
        print(f"wan: {prefix}: empty reference fell back, {n_obj} object variation(s) become prompt-only", flush=True)
        n_var, n_obj = n_var + n_obj, 0
    if fallback_refs and ref is None:
        print(f"wan: {prefix}: {len(fallback_refs)} reference slot(s) fell back, adding as many prompt-only variations", flush=True)
        n_var += len(fallback_refs)
    if n_obj:
        ref_empty = os.path.join(d_img, f"{prefix}_ref_empty.png")
        if not os.path.isfile(ref_empty):
            raise FileNotFoundError(f"--n_obj needs {ref_empty} (make_refs.py --empty)")
        kinds += [(ref_empty, f"_o{j:02d}", wan_object_prompt(task, j, seed), "obj") for j in range(1, n_obj + 1)]
    kinds += [(None, f"_p{j:02d}", wan_variation_prompt(task, j, seed), "var") for j in range(1, n_var + 1)]
    jobs, skipped = [], 0
    for r, sfx, pr, mode in kinds:
        for c, src in srcs.items():
            dst = os.path.join(d_wan, f"{prefix}_wan_{c}{sfx}.mp4")
            if os.path.isfile(dst) and not force:
                skipped += 1
                continue
            jobs.append(dict(task=task, prefix=prefix, control=c, src=src, ref=r, suffix=sfx, mode=mode, prompt=pr,
                             negative=negative, seed=seed, steps=steps, cfg=cfg, shift=shift, width=width, height=height,
                             frames=frames, template=template, dst=dst, run_dir=run_dir, attempt=1))
    print(f"wan: {prefix}: refs={[os.path.basename(r) if r else 'none' for r, _ in refs]} controls={list(srcs)} "
          f"n_obj={n_obj} n_var={n_var} todo={len(jobs)} skipped(existing)={skipped} {width}x{height}x{frames}", flush=True)
    return jobs


def execute(jobs: list[dict], servers: list[tuple[str, int | None, str]], comfy_dir: str, comfy_python: str,
            timeout_s: float = 1800, check: bool = True, retries: int = 3) -> dict:
    """Run the jobs on every server at once: one worker thread per (url, gpu, log); each takes the next job from a
    shared queue, so N servers give N videos in parallel and a faster GPU simply takes more jobs. All servers share the
    same ComfyUI dir (same input folder), so each file is uploaded once (under a lock) and reused by every server."""
    todo = queue.Queue()
    for j in jobs:
        todo.put(j)
    templates, uploaded, lock, results = {}, {}, threading.Lock(), {}
    if check:
        import quality  # layout check against the run's simulator edges (needs h5py/cv2 and <prefix>.hdf5)
    busy = [0]  # workers currently holding a job: a retry re-queues, so a worker only stops when the queue is empty and nobody is busy

    def ensure_uploaded(url: str, path: str) -> str:
        with lock:
            if path not in uploaded:
                uploaded[path] = upload(url, path)
            return uploaded[path]

    def worker(url: str, gpu: int | None, log: str):
        try:
            ensure_server(url, comfy_dir, comfy_python, gpu, log)
        except Exception as e:  # noqa: BLE001
            print(f"wan: server {url} (GPU {gpu}) unavailable, its jobs go to the other servers: {e}", flush=True)
            return
        tag = f"[{urllib.parse.urlparse(url).port}]"
        while True:
            try:
                j = todo.get(timeout=5)
            except queue.Empty:
                with lock:
                    if busy[0] == 0 and todo.empty():
                        return
                continue
            with lock:
                busy[0] += 1
            key = f"{j['prefix']}:{j['control']}{j['suffix']}"
            t0 = time.time()
            try:
                with lock:
                    tpl = templates.setdefault(j["template"], json.load(open(j["template"])))
                control_name = ensure_uploaded(url, j["src"])
                ref_name = ensure_uploaded(url, j["ref"]) if j["ref"] else None
                g = build_graph(tpl, control_name, ref_name, j["prompt"], j["negative"], j["seed"], j["steps"], j["cfg"],
                                j["shift"], j["width"], j["height"], j["frames"],
                                f"video/{j['prefix']}_wan_{j['control']}{j['suffix']}")
                pid = submit(url, g)
                print(f"wan: {tag} {key}: submitted {pid}, {todo.qsize()} left in queue", flush=True)
                ent = wait_done(url, pid, timeout_s)
                status = ent.get("status", {})
                if status.get("status_str") == "error":
                    errs = [m for m in status.get("messages", []) if m and m[0] in ("execution_error", "execution_interrupted")]
                    raise RuntimeError("; ".join(f"{m[0]} {m[1].get('node_type')}: {m[1].get('exception_message', '')}".strip()
                                                 for m in errs) or "unknown error")
                files = output_files(ent)
                if not files:
                    raise RuntimeError("no output file in history entry")
                os.makedirs(os.path.dirname(j["dst"]), exist_ok=True)
                download(url, files[0], j["dst"])
                meta = dict(task=j["task"], prefix=j["prefix"], control=j["control"], control_video=os.path.basename(j["src"]),
                            ref_image=j["ref"], ref_suffix=j["suffix"], mode=j["mode"], prompt=j["prompt"], negative=j["negative"],
                            seed=j["seed"], steps=j["steps"], cfg=j["cfg"], shift=j["shift"], width=j["width"],
                            height=j["height"], frames=j["frames"], fps=FPS, template=os.path.relpath(j["template"]),
                            comfy_url=url, prompt_id=pid, comfy_output=files[0], seconds=round(time.time() - t0, 1),
                            finished_at=datetime.now().isoformat(timespec="seconds"))
                meta["attempt"] = j["attempt"]
                res = quality.check_video(j["run_dir"], j["dst"]) if check else dict(passed=True, score=None)
                meta["check"] = res
                if not res["passed"]:
                    d_rej = os.path.join(os.path.dirname(j["dst"]), "rejected")
                    os.makedirs(d_rej, exist_ok=True)
                    base = os.path.join(d_rej, f"{os.path.splitext(os.path.basename(j['dst']))[0]}_try{j['attempt']}")
                    os.replace(j["dst"], base + ".mp4")
                    with open(base + ".json", "w") as f:
                        json.dump(meta, f, indent=1, ensure_ascii=False)
                    if j["attempt"] < retries:
                        print(f"wan: {tag} {key}: check FAIL score {res['score']} (frame {res['worst_frame']}), moved to rejected/, "
                              f"retry {j['attempt'] + 1}/{retries} with seed {j['seed'] + 1}", flush=True)
                        todo.put(dict(j, seed=j["seed"] + 1, attempt=j["attempt"] + 1))
                    else:
                        print(f"wan: {tag} {key}: FAILED check after {retries} attempts (last score {res['score']})", flush=True)
                        with lock:
                            results[key] = None
                    continue
                with open(os.path.splitext(j["dst"])[0] + ".json", "w") as f:
                    json.dump(meta, f, indent=1, ensure_ascii=False)
                print(f"wan: {tag} {key}: {j['dst']} ({meta['seconds']:.0f}s, check {res['score']}, attempt {j['attempt']})", flush=True)
                with lock:
                    results[key] = j["dst"]
            except Exception as e:  # noqa: BLE001
                print(f"wan: {tag} {key}: FAILED after {time.time() - t0:.0f}s: {str(e)[:500]}", flush=True)
                with lock:
                    results[key] = None
            finally:
                with lock:
                    busy[0] -= 1

    threads = [threading.Thread(target=worker, args=s, daemon=True) for s in servers]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    while not todo.empty():  # every server was unavailable
        j = todo.get_nowait()
        results[f"{j['prefix']}:{j['control']}{j['suffix']}"] = None
    return results


def servers_from(urls: str, gpus: str, log: str) -> list[tuple[str, int | None, str]]:
    """'http://127.0.0.1:8188,http://127.0.0.1:8189' + '1,0' -> [(url, gpu, log)]. The first server logs to --comfy_log,
    the others to logs/comfyui_<port>.log."""
    url_list = [u.strip() for u in urls.split(",") if u.strip()]
    gpu_list = [int(g) for g in str(gpus).split(",") if str(g).strip()]
    if len(gpu_list) not in (1, len(url_list)):
        raise ValueError(f"--comfy_gpu needs one value or one per --comfy_url ({len(url_list)})")
    gpu_list = gpu_list * len(url_list) if len(gpu_list) == 1 else gpu_list
    if any(g != 1 for g in gpu_list):
        raise ValueError(f"--comfy_gpu {gpus}: this project may only use GPU 1 (GPU 0 belongs to other users, docker/gpu.sh)")
    out = []
    for i, (u, g) in enumerate(zip(url_list, gpu_list)):
        lg = log if i == 0 else os.path.join(os.path.dirname(log) or ".", f"comfyui_{urllib.parse.urlparse(u).port}.log")
        out.append((u, None if g < 0 else g, lg))
    return out


